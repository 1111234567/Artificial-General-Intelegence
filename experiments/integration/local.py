"""Forward-only temporal coactivity plasticity for the integration experiment.

For post-by-pre recurrent weights W, this module collects

    q_t = exp(-dt/tau) q_(t-1) + (1-exp(-dt/tau)) tanh(h_before)
    C   = sum_t dt * mean_batch[tanh(h_after) outer q_t] / sum_t dt
    s   = sum_t dt * mean_batch[tanh(h_after)^2] / sum_t dt
    delta W = lr * (C - s[:, None] * W).

When a separate old-experience collector is supplied, C and s are the equal
average of the two independently time-normalized source statistics. There is
one matrix update at the same lr, not one update per source.

The activity trace is an EMA, not a loss derivative or an e-prop eligibility
trace. This is an Oja-style heuristic on nonlinear recurrent activity; the
linear, stationary-input PCA guarantees of Oja (1982) do not apply. Used after
BPTT it is a hybrid, not a replacement for supervised temporal credit.

The shuffled control cyclically shifts q across independent batch trajectories
at each contributing tick. A private saved RNG selects a nonzero shift. This
preserves each tick's pre/post marginals and the post-squared decay exactly,
while removing the same-trajectory pairing. It need not match update norm.

The helper never changes hidden states, reads labels, calls backward, or clears
the live trace at chunk boundaries. A separate instance may reconstruct traces
for disconnected historical blocks with ``reset_history_`` and burn-in; those
reconstructed traces are not the original historical auxiliary state.
"""
from __future__ import annotations

from copy import deepcopy
from dataclasses import asdict, dataclass
import math
from numbers import Integral
from typing import Any

import torch


FORMAT_VERSION = "integration-temporal-oja-v1"
SOURCES = {
    "oja": "https://link.springer.com/article/10.1007/BF00275687",
    "eprop_distinct": "https://www.nature.com/articles/s41467-020-17236-y",
}


@dataclass(frozen=True)
class LocalConfig:
    lr: float = 0.001
    tau: float = 16.0
    shuffled: bool = False
    seed: int = 0

    def __post_init__(self) -> None:
        if not math.isfinite(self.lr) or self.lr < 0:
            raise ValueError("local lr must be finite and nonnegative")
        if not math.isfinite(self.tau) or self.tau <= 0:
            raise ValueError("local tau must be finite and positive")
        if not isinstance(self.shuffled, bool):
            raise ValueError("shuffled must be boolean")
        if isinstance(self.seed, bool) or not isinstance(self.seed, Integral) or not 0 <= self.seed < 2**63:
            raise ValueError("local seed must be an integer in [0, 2**63)")


class TemporalOja:
    """Persistent live trace plus chunk statistics, with exact continuation.

    ``observe`` accepts hidden values immediately before and after an unchanged
    model step. ``accumulate=False`` advances only the trace and exposure
    counters, as needed for replay burn-in. ``apply_`` uses the weights present
    at the call (normally after the corresponding BP update), then clears only
    chunk statistics. Activity was generated by the pre-BP forward weights.

    Time averaging makes lr a per-application coefficient, not per-unit-time
    plasticity. More frequent applications therefore change the update budget;
    all application and exposure counts are reported explicitly.
    """

    def __init__(self, batch_size: int, width: int, config: LocalConfig | None = None,
                 device: str | torch.device = "cpu", dtype: torch.dtype = torch.float32):
        for name, value in (("batch_size", batch_size), ("width", width)):
            if isinstance(value, bool) or not isinstance(value, Integral) or value < 1:
                raise ValueError(f"{name} must be a positive integer")
        self.batch_size, self.width = int(batch_size), int(width)
        self.config = LocalConfig() if config is None else config
        if not isinstance(self.config, LocalConfig):
            raise TypeError("config must be LocalConfig")
        if self.config.shuffled and self.batch_size < 2:
            raise ValueError("shuffled local control requires at least two trajectories")
        if not torch.empty((), dtype=dtype).is_floating_point():
            raise ValueError("local activity dtype must be floating point")
        self.device, self.dtype = torch.device(device), dtype
        self.trace = torch.zeros(self.batch_size, self.width, device=self.device, dtype=dtype)
        # Canonicalize an unindexed "cuda" to the allocated tensor's device.
        self.device = self.trace.device
        self.coactivity_sum = torch.zeros(self.width, self.width, device=self.device, dtype=dtype)
        self.post_second_sum = torch.zeros(self.width, device=self.device, dtype=dtype)
        self.rng = torch.Generator(device="cpu").manual_seed(int(self.config.seed))
        self.observed_ticks = self.plasticity_ticks = self.updates = self.matrix_writes = 0
        self.observed_elapsed = self.plasticity_elapsed = 0.0
        self.pending_ticks, self.pending_elapsed = 0, 0.0
        self.history_restarts, self.last_shift = 0, 0
        self.delta_frob_sum, self.delta_frob_squared_sum = 0.0, 0.0
        self.last_update: dict[str, Any] | None = None

    def _check_hidden(self, tensor: torch.Tensor, name: str) -> None:
        if tensor.shape != (self.batch_size, self.width):
            raise ValueError(f"{name} must have shape {(self.batch_size, self.width)}")
        if tensor.device != self.device or tensor.dtype != self.dtype:
            raise ValueError(f"{name} device/dtype differs from the local trace")

    def _check_weight(self, recurrent: torch.Tensor) -> None:
        if recurrent.shape != (self.width, self.width):
            raise ValueError("recurrent weight must be a post-by-pre square matrix")
        if recurrent.device != self.device or recurrent.dtype != self.dtype:
            raise ValueError("recurrent weight device/dtype differs from the local trace")

    @torch.no_grad()
    def observe(self, pre_h: torch.Tensor, post_h: torch.Tensor, dt: float, *,
                accumulate: bool = True) -> None:
        self._check_hidden(pre_h, "pre_h")
        self._check_hidden(post_h, "post_h")
        elapsed = float(dt)
        if not math.isfinite(elapsed) or elapsed < 0:
            raise ValueError("local elapsed time must be finite and nonnegative")
        if not isinstance(accumulate, bool):
            raise ValueError("accumulate must be boolean")
        # expm1 avoids loss of precision when dt is small relative to tau.
        innovation = -math.expm1(-elapsed / self.config.tau)
        self.trace.mul_(1.0 - innovation).add_(pre_h.detach().tanh(), alpha=innovation)
        self.observed_ticks += 1
        self.observed_elapsed += elapsed
        if not accumulate or elapsed == 0:
            return
        post = post_h.detach().tanh()
        pre = self.trace
        self.last_shift = (int(torch.randint(1, self.batch_size, (), generator=self.rng))
                           if self.config.shuffled else 0)
        if self.last_shift:
            pre = torch.roll(pre, self.last_shift, dims=0)
        self.coactivity_sum.add_(post.T @ pre, alpha=elapsed / self.batch_size)
        self.post_second_sum.add_(post.square().mean(0), alpha=elapsed)
        self.pending_ticks += 1
        self.pending_elapsed += elapsed
        self.plasticity_ticks += 1
        self.plasticity_elapsed += elapsed

    @torch.no_grad()
    def clear_accumulator(self) -> None:
        """Clear consumed chunk statistics, preserving trace, RNG and totals."""
        self.coactivity_sum.zero_()
        self.post_second_sum.zero_()
        self.pending_ticks, self.pending_elapsed = 0, 0.0

    @torch.no_grad()
    def reset_history_(self) -> None:
        """Start a disconnected replay block; never use for the live stream."""
        if self.pending_ticks:
            raise RuntimeError("apply or clear pending local statistics before starting replay history")
        self.trace.zero_()
        self.clear_accumulator()
        self.history_restarts += 1

    @torch.no_grad()
    def statistics(self) -> dict[str, Any]:
        """Export detached raw numerators and exposure, without consuming them."""
        return {"coactivity_sum": self.coactivity_sum.detach().clone(),
                "post_second_sum": self.post_second_sum.detach().clone(),
                "elapsed": self.pending_elapsed, "ticks": self.pending_ticks,
                "batch_size": self.batch_size}

    @torch.no_grad()
    def proposal(self, recurrent: torch.Tensor, *, other: TemporalOja | None = None
                 ) -> tuple[torch.Tensor, dict[str, Any]]:
        """Return an audited update without changing any state or parameters."""
        self._check_weight(recurrent)
        collectors = [self] if other is None else [self, other]
        if other is not None:
            if other is self:
                raise ValueError("mixture requires separate live and historical collectors")
            other._check_weight(recurrent)
            if (self.batch_size != other.batch_size or self.config.lr != other.config.lr
                    or self.config.tau != other.config.tau or self.config.shuffled != other.config.shuffled):
                raise ValueError("mixture collectors must share shape/rule except private seed")
            if not self.pending_elapsed or not other.pending_elapsed:
                raise ValueError("both mixture sources need positive exposure")
        if not self.pending_elapsed:
            return torch.zeros_like(recurrent), {
                "applied": False, "pending_ticks": 0, "batch_ticks": 0,
                "elapsed_per_trajectory": 0.0, "batch_elapsed": 0.0,
                "outer_product_terms": 0, "lr": self.config.lr,
                "delta_frob": 0.0, "delta_max_abs": 0.0,
            }
        source_weight = 1.0 / len(collectors)
        coactivity = sum((source.coactivity_sum / source.pending_elapsed for source in collectors)) * source_weight
        post_second = sum((source.post_second_sum / source.pending_elapsed for source in collectors)) * source_weight
        decay = post_second[:, None] * recurrent.detach()
        direction = coactivity - decay
        delta = self.config.lr * direction
        if (not bool(torch.isfinite(delta).all())
                or not all(bool(torch.isfinite(source.trace).all()) for source in collectors)
                or not bool(torch.isfinite(recurrent.detach() + delta).all())):
            raise FloatingPointError("nonfinite temporal Oja activity/update")
        norm_before = float(torch.linalg.vector_norm(recurrent.detach()))
        delta_norm = float(torch.linalg.vector_norm(delta))
        metrics = {
            "applied": True, "pending_ticks": sum(source.pending_ticks for source in collectors),
            "batch_ticks": sum(source.pending_ticks * source.batch_size for source in collectors),
            "elapsed_per_trajectory": sum(source.pending_elapsed for source in collectors),
            "batch_elapsed": sum(source.pending_elapsed * source.batch_size for source in collectors),
            "source_weights": [source_weight] * len(collectors),
            "source_ticks": [source.pending_ticks for source in collectors],
            "source_elapsed_per_trajectory": [source.pending_elapsed for source in collectors],
            # Scalar products in the Hebbian outer-product sum; not all FLOPs.
            "outer_product_terms": sum(source.pending_ticks * source.batch_size * source.width**2
                                       for source in collectors),
            "lr": self.config.lr, "tau": self.config.tau, "shuffled": self.config.shuffled,
            "coactivity_frob": float(torch.linalg.vector_norm(coactivity)),
            "post_second_mean": float(post_second.mean()),
            "decay_frob": float(torch.linalg.vector_norm(decay)),
            "direction_frob": float(torch.linalg.vector_norm(direction)),
            "delta_frob": delta_norm, "delta_max_abs": float(delta.abs().max()),
            "weight_frob_before": norm_before,
            "relative_delta_frob": delta_norm / norm_before if norm_before else None,
        }
        return delta, metrics

    @torch.no_grad()
    def apply_(self, recurrent: torch.Tensor, *, other: TemporalOja | None = None) -> dict[str, Any]:
        """Apply once at a completed optimizer boundary; retain live trace."""
        delta, metrics = self.proposal(recurrent, other=other)
        if metrics["applied"]:
            if self.config.lr:
                recurrent.add_(delta)
                self.matrix_writes += 1
            self.updates += 1
            self.delta_frob_sum += metrics["delta_frob"]
            self.delta_frob_squared_sum += metrics["delta_frob"]**2
            self.clear_accumulator()
            if other is not None:
                other.clear_accumulator()
        self.last_update = deepcopy(metrics)
        return metrics

    def state_dict(self) -> dict[str, Any]:
        state = {"format": FORMAT_VERSION, "config": asdict(self.config),
                 "batch_size": self.batch_size, "width": self.width,
                 "dtype": str(self.dtype), "rng": self.rng.get_state().clone()}
        for name in ("trace", "coactivity_sum", "post_second_sum"):
            state[name] = getattr(self, name).detach().cpu().clone()
        for name in ("observed_ticks", "plasticity_ticks", "updates", "matrix_writes",
                     "observed_elapsed", "plasticity_elapsed", "pending_ticks", "pending_elapsed",
                     "history_restarts", "last_shift", "delta_frob_sum", "delta_frob_squared_sum",
                     "last_update"):
            state[name] = deepcopy(getattr(self, name))
        return state

    @torch.no_grad()
    def load_state_dict(self, state: dict[str, Any]) -> None:
        expected = {"format": FORMAT_VERSION, "config": asdict(self.config),
                    "batch_size": self.batch_size, "width": self.width, "dtype": str(self.dtype)}
        if any(state.get(name) != value for name, value in expected.items()):
            raise ValueError("local checkpoint configuration/dimensions/format differ")
        for name in ("trace", "coactivity_sum", "post_second_sum"):
            value, destination = state[name], getattr(self, name)
            if value.shape != destination.shape or value.dtype != self.dtype or not bool(torch.isfinite(value).all()):
                raise ValueError(f"invalid local checkpoint tensor: {name}")
        for name in ("observed_ticks", "plasticity_ticks", "updates", "matrix_writes",
                     "pending_ticks", "history_restarts", "last_shift"):
            if isinstance(state[name], bool) or not isinstance(state[name], Integral) or state[name] < 0:
                raise ValueError(f"invalid local checkpoint counter: {name}")
        for name in ("observed_elapsed", "plasticity_elapsed", "pending_elapsed",
                     "delta_frob_sum", "delta_frob_squared_sum"):
            if not math.isfinite(state[name]) or state[name] < 0:
                raise ValueError(f"invalid local checkpoint scalar: {name}")
        if (state["plasticity_ticks"] > state["observed_ticks"]
                or state["pending_ticks"] > state["plasticity_ticks"]
                or state["plasticity_elapsed"] > state["observed_elapsed"]
                or state["pending_elapsed"] > state["plasticity_elapsed"]
                or bool(state["pending_ticks"]) != bool(state["pending_elapsed"])
                or state["matrix_writes"] > state["updates"]
                or not 0 <= state["last_shift"] < self.batch_size):
            raise ValueError("inconsistent local checkpoint counters")
        # Validate the private RNG before mutating any continuation state.
        trial_rng = torch.Generator(device="cpu")
        trial_rng.set_state(state["rng"].cpu())
        for name in ("trace", "coactivity_sum", "post_second_sum"):
            getattr(self, name).copy_(state[name].to(self.device))
        for name in ("observed_ticks", "plasticity_ticks", "updates", "matrix_writes",
                     "observed_elapsed", "plasticity_elapsed", "pending_ticks", "pending_elapsed",
                     "history_restarts", "last_shift", "delta_frob_sum", "delta_frob_squared_sum",
                     "last_update"):
            setattr(self, name, deepcopy(state[name]))
        self.rng.set_state(trial_rng.get_state())

    def summary(self) -> dict[str, Any]:
        buffers = (self.trace, self.coactivity_sum, self.post_second_sum)
        return {
            "format": FORMAT_VERSION, "config": asdict(self.config),
            "trace_shape": list(self.trace.shape),
            "trace_bytes": self.trace.numel() * self.trace.element_size(),
            "buffer_bytes": sum(value.numel() * value.element_size() for value in buffers),
            "private_rng_bytes": self.rng.get_state().numel(),
            "observed_ticks": self.observed_ticks,
            "observed_batch_ticks": self.observed_ticks * self.batch_size,
            "observed_elapsed_per_trajectory": self.observed_elapsed,
            "plasticity_ticks": self.plasticity_ticks,
            "plasticity_batch_ticks": self.plasticity_ticks * self.batch_size,
            "plasticity_batch_elapsed": self.plasticity_elapsed * self.batch_size,
            "outer_product_terms": self.plasticity_ticks * self.batch_size * self.width**2,
            "local_updates": self.updates, "matrix_writes": self.matrix_writes,
            "pending_ticks": self.pending_ticks, "pending_elapsed": self.pending_elapsed,
            "history_restarts": self.history_restarts,
            "delta_frob_sum": self.delta_frob_sum,
            "delta_frob_squared_sum": self.delta_frob_squared_sum,
            "last_update": deepcopy(self.last_update),
            "budget_note": "Time-averaged per-application lr; outer-product terms exclude other FLOPs. "
                           "Equal calls/lr do not imply equal update norm or compute to BP.",
            "trace_note": "Presynaptic EMA, not derivative eligibility; chunk apply retains trace. "
                          "Historical zero-start burn-in reconstructs an approximate separate trace.",
        }
