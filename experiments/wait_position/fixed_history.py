"""Read timing choices on identical, previously recorded held-out mixed histories."""
import argparse
from collections import Counter
from datetime import datetime, timezone
import json

import numpy as np
import torch

from experiments.wait_position import switch_pairs as study
from experiments.review_selection.pairs import sha
from experiments.learn_remember.gru_train import GRUAgent
from experiments.learn_remember import evaluate_gru as original
from experiments.experience_transfer import eval_transfer as source
from experiments.experience_transfer.train_transfer import SEEDS


OUT=study.BASE/"history-v1"
PREVIOUS=study.ROOT/"data/review-selection/eval-v1"
EPS=1e-6


def inputs(seed):
    prefix=PREVIOUS/f"seed_{seed:03d}/uniform_B008_mixed"
    common=source.OUT/f"common_seed_{seed:03d}_related.pt"
    return prefix.with_suffix(".npz"),prefix.with_suffix(".requests.json"),common


def declare():
    OUT.mkdir(parents=True,exist_ok=True)
    paths=[p for seed in range(3) for p in inputs(seed)]
    pins={str(p.relative_to(study.ROOT)):sha(p) for p in paths}
    with (OUT/"protocol.json").open("x",encoding="utf-8") as f:
        json.dump(dict(created_utc=datetime.now(timezone.utc).isoformat(),
            question="On the same real mixed test histories, is premature FINISH less tempting, and does the policy still want the correct FINISH at the first midpoint-oracle opportunity?",
            source="Saved heldout trajectories and actual public receipts generated by previous uniform B008. All three final models are frozen; no actions generated in this diagnostic affect the input.",
            primary="Include only independently recorded mature, conflicting requests, separate A and B. Record processing WAIT tick count, any pre-ready FINISH per request that actually reaches processing, and the first actual teacher FINISH eligible tick on each reference request. A reference request can finish before teacher midpoint; exclude it only from that denominator.",
            score="Exact deployed eleven-action argmax per tick. Also inspect conditional eight-way FINISH content and maximum FINISH minus best WAIT/BEGIN on the reference trajectory. Heldout is separate from historical training bank.",
            input_sha256=pins,script_sha256=sha(__file__)),f,indent=2)


@torch.inference_mode()
def replay(model,warm,obs):
    h=original.warmup(model,warm)
    out=[]
    for tick in torch.from_numpy(obs):
        logits,h=model.step(tick,h,.25)
        out.append(logits.numpy())
    return np.stack(out)


def score(rows,facts,logits,seed):
    chosen=logits.argmax(-1)
    metrics={k:Counter() for k in ("A","B")}
    details=[]
    s=SEEDS[seed]
    now=facts["now"]
    for r in rows:
        if r["raw"] not in s["conflict_raw"]:
            continue
        lane,j=r["actor"]-730000,r["job"]
        assert 0<=lane<8
        role="A" if r["family"]==s["history_cue"] else "B"
        assert r["family"] in (s["history_cue"],s["B_cue"])
        m=metrics[role]
        m["matured"]+=1
        active=(facts["request_id"][:,lane,j]==r["request_id"]) & facts["active"][:,lane,j] & facts["started"][:,lane,j]
        ready,deadline=facts["ready_time"][:,lane,j],facts["deadline"][:,lane,j]
        processing=active & (now<ready-EPS)
        legal=active & (now>=ready-EPS) & (now<=deadline+EPS)
        teach=legal & ((now>=.5*(ready+deadline)-EPS) | (now+.25>deadline+EPS))
        early=processing & (chosen[:,lane,j]>=3)
        m.update(processing_requests=int(processing.any()),processing_ticks=int(processing.sum()),
                 would_early_ticks=int(early.sum()),would_early_requests=int(early.any()),
                 legal_requests=int(legal.any()))
        first=np.flatnonzero(teach)
        if len(first):
            i=first[0]
            target=3+4*int(facts["version"][i,lane,j])+int(facts["payload"][i,lane,j])
            a=int(chosen[i,lane,j])
            m.update(first_teacher=1,would_finish=a>=3,would_correct=a==target,
                     conditional_correct=int(logits[i,lane,j,3:].argmax())+3==target)
        details.append([role,r["actor"],j,r["request_id"],int(processing.sum()),int(early.sum()),int(early.any()),
                        int(first[0]) if len(first) else None])
    return metrics,details


def run(seed):
    torch.set_num_threads(1)
    proto=study.read(OUT/"protocol.json")
    paths=inputs(seed)
    assert sha(__file__)==proto["script_sha256"]
    assert all(sha(p)==proto["input_sha256"][str(p.relative_to(study.ROOT))] for p in paths)
    with np.load(paths[0]) as z:
        obs=z["obs"];old=z["logits"]
        facts={k:z[k] for k in ("now","request_id","active","started","ready_time","deadline","version","payload")}
    rows=study.read(paths[1])["matured"]
    warm=torch.load(paths[2],weights_only=False,map_location="cpu")
    records=[]
    for arm in study.ARMS:
        cp=study.model_path(seed,arm)
        d=torch.load(cp,weights_only=False,map_location="cpu")
        model=GRUAgent(**d["model_config"]);model.load_state_dict(d["model"])
        values=replay(model.eval(),warm,obs)
        metrics,ids=score(rows,facts,values,seed)
        records.append(dict(seed=seed,arm=arm,metrics=metrics,detail=ids,model_sha=sha(cp),
                            same_actions_as_old=int((values.argmax(-1)==old.argmax(-1)).sum()),
                            actions_total=int(np.prod(values.shape[:-1])),
                            max_abs_logit_delta=float(np.max(np.abs(values-old)))))
    with (OUT/f"seed_{seed:03d}.json").open("x",encoding="utf-8") as f:
        json.dump(records,f,separators=(",",":"))


if __name__=="__main__":
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("command",choices=("declare","run"));p.add_argument("--seed",type=int,choices=range(3))
    a=p.parse_args()
    if a.command=="declare":declare()
    else:run(a.seed)
