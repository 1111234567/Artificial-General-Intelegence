"""Read route facts from sealed graph states before the late goal is presented."""

from argparse import ArgumentParser
from dataclasses import fields
from datetime import datetime, timezone
from itertools import product
from pathlib import Path
from types import SimpleNamespace

import numpy as np
import torch

from . import double_visit_fit as fit
from . import double_visit_world as world
from . import interleave_revisit_train as storage
from . import noon_market_stats as stats


PLAN = fit.EVIDENCE / "localization-plan.md"
DATA = fit.FIT_ROOT / "memory"
FIRST_TICK = 2 * world.VISIT_TICKS + world.INSPECTION_TICKS
RIDGE = .01
BOOTSTRAP_SEED = 86202719
BLOCKS = ("h", "trace", "fast", "candidate")
READOUTS = ("primary", "full", "blank", "physical_record")
TIMES = ("after_first", "after_second")


class Tape:
    """Receive exactly the pulses generated by the physical world without running a graph."""

    def start(self, count):
        return SimpleNamespace(h=torch.zeros(count, 2 * world.REGION))

    def advance(self, state, pulse, ticks):
        return state


def episode_keys(e):
    return torch.column_stack([getattr(e, field.name) for field in fields(e) if field.name != "goals"]).numpy()


def physical_tables(tape):
    """Recover identity targets using only old contacts and the two chronological observations."""
    rows = np.arange(tape.shape[1])
    routes = np.empty((len(rows), 2), dtype=np.int64)
    prior = np.empty_like(routes)
    for start in (0, world.VISIT_TICKS):
        door = tape[start + 1, :, world.DOOR_PORTS].argmax(1).numpy()
        room = tape[start + 2, :, world.ROOM_PORTS].argmax(1).numpy()
        endpoint = tape[start + 4, :, world.ENDPOINT_PORTS].argmax(1).numpy()
        routes[rows, door] = room
        prior[rows, room] = endpoint

    tables, room_order, observed = [], [], []
    current = prior.copy()
    for start in (2 * world.VISIT_TICKS, FIRST_TICK):
        room = tape[start + 1, :, world.ROOM_PORTS].argmax(1).numpy()
        endpoint = tape[start + 3, :, world.ENDPOINT_PORTS].argmax(1).numpy()
        current[rows, room] = endpoint
        tables.append(current.copy())
        room_order.append(room)
        observed.append(endpoint)
    return routes, prior, np.stack(room_order, axis=1), np.stack(observed, axis=1), tables


def layout():
    panel, _, map_ids = world.panel()
    key = episode_keys(panel)
    _, canonical = np.unique(key, axis=0, return_inverse=True)
    representative = (panel.goals == panel.goals.new_tensor(world.GOAL_ORDERS[0])).all(1).numpy()
    order = np.argsort(canonical[representative])
    selected = np.flatnonzero(representative)[order]
    scene = panel[selected]
    _, history = world.history(Tape(), scene, return_receipts=True)
    tape = history.inputs
    if tape[:, :, world.GOAL_PORT:].any():
        raise AssertionError("The saved state must precede the late goal and all payouts")
    batch_tape = tape.transpose(0, 1).reshape(len(scene), -1).numpy()
    unique_full = np.unique(batch_tape, axis=0)
    first = tape[:FIRST_TICK].transpose(0, 1).reshape(len(scene), -1).numpy()
    _, prefix, prefix_of = np.unique(first, axis=0, return_index=True, return_inverse=True)
    if len(unique_full) != len(scene) or len(selected) != 864 or len(prefix) != 144:
        raise AssertionError("The two state snapshots no longer have 864 and 144 unique physical histories")

    routes, prior, room_order, observed, (first_all, second) = physical_tables(tape)
    np.testing.assert_array_equal(routes, scene.door_rooms.numpy())
    np.testing.assert_array_equal(prior, scene.prior_endpoints.numpy())
    np.testing.assert_array_equal(room_order, scene.inspected_rooms.numpy())
    np.testing.assert_array_equal(observed, scene.observed_endpoints.numpy())
    np.testing.assert_array_equal(first_all[prefix][prefix_of], first_all)
    np.testing.assert_array_equal(second[np.arange(len(scene))[:, None], routes], world.oracle(scene).endpoints.numpy())
    map_ids = map_ids[selected].numpy()
    np.testing.assert_array_equal(map_ids[prefix][prefix_of], map_ids)

    formal_pairs = canonical[world.first_observation_pairs(panel).numpy()]
    pairs, frequency = np.unique(np.sort(formal_pairs, axis=1), axis=0, return_counts=True)
    if len(pairs) != 144 or not np.all(frequency == 2):
        raise AssertionError("Each physical critical pair must have two possible late-goal polarity assignments")
    np.testing.assert_array_equal(map_ids[pairs[:, 0]], map_ids[pairs[:, 1]])
    np.testing.assert_array_equal(room_order[pairs[:, 0]], room_order[pairs[:, 1]])
    return dict(
        tape=tape, scenes=scene, panel_row=selected, prefix_row=prefix, prefix_of=prefix_of, map_id=map_ids,
        rooms=room_order, observed=observed, prior=prior, maps=routes,
        after_first=first_all[prefix], after_second=second, pairs=pairs, formal_pairs=formal_pairs,
    )


def progress(model, state, tape):
    for pulse in tape:
        state = model.advance(state, pulse, 1)
    return state


def fast_mask(model):
    mask = model.mask.clone()
    # Replica recurrence derives fast current from the main block plus the pending increment.
    mask[world.REGION:, world.REGION:] = False
    return mask


def blocks(state, active, pending):
    if state.fast[:, ~active].any() or state.candidate[:, ~pending].any():
        raise AssertionError("State outside the registered fast and candidate connection masks is live")
    return tuple(value.numpy() for value in (
        state.h, state.trace, state.fast[:, active], state.candidate[:, pending],
    ))


@torch.no_grad()
def states(model, design):
    tape, prefix, copied = (design[key] for key in ("tape", "prefix_row", "prefix_of"))
    first = progress(model, model.start(len(prefix)), tape[:FIRST_TICK, prefix])
    continued = world.State(**{field.name: getattr(first, field.name)[copied] for field in fields(world.State)})
    second = progress(model, continued, tape[FIRST_TICK:])
    sample = np.arange(0, len(copied), len(copied) // 12)
    actual = world.history(model, design["scenes"][sample])
    for field in fields(world.State):
        torch.testing.assert_close(getattr(actual, field.name), getattr(second, field.name)[sample],
                                   rtol=2e-5, atol=2e-6)
    active, pending = fast_mask(model), model.mask[:world.REGION, :world.REGION]
    return dict(after_first=blocks(first, active, pending), after_second=blocks(second, active, pending))


def ridge_readout(features, endpoints, development):
    """Return six offline scores for every row from fixed room-by-endpoint linear targets."""
    normalized = []
    for block in features:
        block = np.asarray(block, dtype=np.float64)
        training = block[development]
        center = training.mean(axis=0)
        delta = training - center
        scale = np.sqrt(np.square(delta).sum(axis=1).mean())
        normalized.append((block - center) / scale if scale > 1e-12 else np.zeros_like(block))
    x = torch.from_numpy(np.concatenate(normalized, axis=1))
    training = x[development]
    y = torch.nn.functional.one_hot(torch.from_numpy(endpoints[development]), num_classes=3).reshape(-1, 6).double()
    y_center = y.mean(dim=0)
    penalty = len(y) * RIDGE
    # Use the mathematically equivalent dual solution when there are more coordinates than examples.
    if training.shape[1] > len(training):
        gram = training @ training.T
        gram.diagonal().add_(penalty)
        coefficient = training.T @ torch.linalg.solve(gram, y - y_center)
    else:
        gram = training.T @ training
        gram.diagonal().add_(penalty)
        coefficient = torch.linalg.solve(gram, training.T @ (y - y_center))
    return (x @ coefficient + y_center).reshape(-1, 2, 3).numpy()


def scores(receipts, blank, design):
    output = {}
    for time in TIMES:
        target = design[time]
        map_ids = design["map_id"][design["prefix_row"]] if time == TIMES[0] else design["map_id"]
        development = np.isin(map_ids, world.EVEN_MAP_IDS)
        same_durations = tuple(np.broadcast_to(block, (len(target), block.shape[1])) for block in blank[time])
        physical_record = np.eye(3)[target].reshape(len(target), 6)
        activity = receipts[time][0]
        for readout, features in dict(
            primary=(activity[:, :world.REGION],), full=receipts[time], blank=same_durations,
            physical_record=(physical_record,),
        ).items():
            output[f"{readout}/{time}"] = ridge_readout(features, target, development)
    return output


def metadata(window, design):
    if window == TIMES[0]:
        selected = design["prefix_row"]
        first_room = design["rooms"][selected, 0]
        return design["map_id"][selected], first_room, 1 - first_room
    first_room, second_room = design["rooms"].T
    return design["map_id"], first_room, second_room


def measures(scores_by_time, design):
    first, second = (scores_by_time[time].argmax(axis=2) for time in TIMES)
    values = {}
    for time, prediction in zip(TIMES, (first, second), strict=True):
        map_id, first_room, second_room = metadata(time, design)
        rows = np.arange(len(prediction))
        correct = prediction == design[time]

        def accuracy(name, mask, success, old_map=map_id):
            values[name] = {int(idx): [int((success & mask & (old_map == idx)).sum()), int((mask & (old_map == idx)).sum())]
                            for idx in np.unique(old_map)}

        if time == TIMES[0]:
            all_rows = np.ones(len(rows), dtype=bool)
            accuracy("first/updated", all_rows, correct[rows, first_room])
            accuracy("first/other", all_rows, correct[rows, second_room])
            accuracy("first/both_rooms", all_rows, correct.all(1))
            pair = design["prefix_of"][design["pairs"]]
            pair_maps = map_id[pair[:, 0]]
            accuracy("first/pairs/first_room_both_branches", np.ones(len(pair), dtype=bool),
                     correct[rows, first_room][pair].all(1), pair_maps)
            continue

        different = first_room != second_room
        overwritten = ~different & (design["observed"][:, 0] != design["observed"][:, 1])
        old_differs_from_new = design["prior"][rows, second_room] != design["observed"][:, 1]
        accuracy("second/different/first", different, correct[rows, first_room])
        accuracy("second/different/last", different, correct[rows, second_room])
        accuracy("second/different/both_rooms", different, correct.all(1))
        accuracy("second/any/both_rooms", np.ones(len(rows), dtype=bool), correct.all(1))
        accuracy("second/overwrite/latest", overwritten, correct[rows, second_room])
        accuracy("second/overwrite/obsolete_first", overwritten, prediction[rows, second_room] == design["observed"][:, 0])
        accuracy("second/overwrite/old_before_visits_when_distinct", overwritten & old_differs_from_new,
                 prediction[rows, second_room] == design["prior"][rows, second_room])
        accuracy("second/overwrite/other_room", overwritten, correct[rows, 1 - second_room])
        accuracy("second/overwrite/both_rooms", overwritten, correct.all(1))

        pair = design["pairs"]
        pair_maps = map_id[pair[:, 0]]
        pair_selector = np.ones(len(pair), dtype=bool)
        first_right = correct[rows, first_room]
        accuracy("pairs/first_room_both_branches", pair_selector, first_right[pair].all(1), pair_maps)
        accuracy("pairs/all_four_room_labels", pair_selector, correct.all(1)[pair].all(1), pair_maps)
        formal = design["formal_pairs"]
        for name, success in (("pairs/first_room_both_branches", first_right),
                              ("pairs/all_four_room_labels", correct.all(1))):
            formal_maps = map_id[formal[:, 0]]
            for idx, (numerator, denominator) in values[name].items():
                keep = formal_maps == idx
                if (success[formal[keep]].all(1).sum(), keep.sum()) != (2 * numerator, 2 * denominator):
                    raise AssertionError("Deduplicating the late goal changed the critical-pair rates")
    return values


@torch.no_grad()
def measure_model(model, design):
    receipt = states(model, design)
    zero = design["tape"][:, :1].new_zeros(world.HISTORY_TICKS, 1, world.PORTS)
    blank_first = progress(model, model.start(1), zero[:FIRST_TICK])
    blank_second = progress(model, blank_first, zero[FIRST_TICK:])
    active, pending = fast_mask(model), model.mask[:world.REGION, :world.REGION]
    blank = dict(after_first=blocks(blank_first, active, pending), after_second=blocks(blank_second, active, pending))
    score = scores(receipt, blank, design)
    metrics = {name: measures({time: score[f"{name}/{time}"] for time in TIMES}, design) for name in READOUTS}
    for time in TIMES:
        np.testing.assert_array_equal(score[f"physical_record/{time}"].argmax(axis=2), design[time])
        blank = score[f"blank/{time}"].argmax(axis=2)
        np.testing.assert_array_equal(blank, np.broadcast_to(blank[0], blank.shape))
    return receipt, score, metrics


def identities():
    files = (Path(__file__), PLAN, Path(world.__file__), Path(fit.__file__), fit.PROTOCOL)
    return {path.relative_to(fit.ROOT).as_posix(): fit.digest(path) for path in files}


def output_path(condition, birth):
    return DATA / f"{condition}-{birth}.npz"


def production(design):
    require_sealed_fits()
    source = identities()
    storage._write_raw(DATA / "layout.npz", **{
        name: value.numpy() if torch.is_tensor(value) else value
        for name, value in design.items() if name != "scenes"
    })
    raw_hashes, model_hashes, all_metrics, feature_dimensions = {}, {}, {}, {}
    for condition, birth in product(fit.CONDITIONS, fit.BIRTHS):
        model, caption, digest = fit.load_final(birth, condition)
        receipt, score, metrics = measure_model(model, design)
        dimensions = {
            time: {name: value.shape[1] for name, value in zip(BLOCKS, receipt[time], strict=True)}
            for time in TIMES
        }
        if feature_dimensions.setdefault(birth, dimensions) != dimensions:
            raise AssertionError(f"Feature dimensions differ across training conditions for birth {birth}")
        path = output_path(condition, birth)
        storage._write_raw(path, **{
            **score, **{f"{time}/{name}": block for time in TIMES for name, block in zip(BLOCKS, receipt[time], strict=True)},
            "fast_mask": fast_mask(model).numpy(), "candidate_mask": model.mask[:world.REGION, :world.REGION].numpy(),
            "checkpoint_sha256": digest, "checkpoint_state_sha256": caption["state_sha256"],
            "source_sha256": source[Path(__file__).relative_to(fit.ROOT).as_posix()],
        })
        all_metrics[(condition, birth)] = metrics
        raw_hashes[path.name] = fit.digest(path)
        model_hashes[path.name] = digest
        print(condition, birth, "sealed snapshot passed physical and blank controls", flush=True)

    split_output = {}
    for split, map_ids in (("even_calibration", world.EVEN_MAP_IDS),
                           ("odd_heldout", tuple(i for i in range(len(world.OLD_MAPS)) if i not in world.EVEN_MAP_IDS))):
        values, counts = {}, {}
        for condition, readout in product(fit.CONDITIONS, READOUTS):
            lives = [all_metrics[(condition, birth)][readout] for birth in fit.BIRTHS]
            group = f"{condition}/{readout}"
            values[group], counts[group] = {}, {}
            for metric in lives[0]:
                cells = np.asarray([[life[metric][idx] for idx in map_ids] for life in lives])
                if not np.all(cells[:, :, 1] == cells[0, 0, 1]):
                    raise AssertionError("Unequal old-map or birth weighting")
                counts[group][metric] = cells.tolist()
                values[group][metric] = cells[:, :, 0] / cells[:, :, 1]
        contrasts = [(f"identity/{name}", f"baseline/{name}") for name in ("primary", "full")]
        contrasts.extend((f"{arm}/full", f"{arm}/primary") for arm in fit.CONDITIONS)
        summary = stats.summarize(values, len(map_ids), fit.BIRTHS, BOOTSTRAP_SEED, contrasts)
        split_output[split] = dict(old_map_ids=map_ids, result=summary, count_by_birth_and_map=counts)

    storage._write_json(fit.EVIDENCE / "memory-results.json", dict(
        completed_utc=datetime.now(timezone.utc).isoformat(), sealed_updates=fit.STEPS,
        ridge=RIDGE, bootstrap_seed=BOOTSTRAP_SEED, births=fit.BIRTHS, sources_sha256=source,
        archives_sha256=raw_hashes | {"layout.npz": fit.digest(DATA / "layout.npz")}, checkpoints_sha256=model_hashes,
        snapshot_ticks=dict(after_first=FIRST_TICK, after_second=world.HISTORY_TICKS),
        total_unique_history_counts={time: int(len(design[time])) for time in TIMES},
        critical_pairs=len(design["pairs"]), formal_goal_assigned_pairs=len(design["formal_pairs"]),
        feature_dimensions=feature_dimensions,
        split=split_output,
    ))


def require_sealed_fits():
    """Fail before any long-running output if a required frozen production file is absent."""
    for condition, birth in product(fit.CONDITIONS, fit.BIRTHS):
        if not fit.destination(birth, condition).is_file():
            raise FileNotFoundError(f"Missing sealed fit {fit.destination(birth, condition)}")


def smoke(design):
    model = world.DoubleVisitGraph(fit.BIRTHS[0]).eval().requires_grad_(False)
    receipt, _, metrics = measure_model(model, design)
    print("smoke shapes", {time: [value.shape for value in receipt[time]] for time in TIMES}, flush=True)
    for name in ("primary", "full", "blank", "physical_record"):
        print(name, metrics[name]["pairs/first_room_both_branches"], flush=True)


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("--smoke", action="store_true", help="Run a non-production graph without writing evidence")
    args = parser.parse_args()
    torch.set_num_threads(1)
    torch.set_num_interop_threads(1)
    torch.use_deterministic_algorithms(True)
    design = layout()
    if args.smoke:
        smoke(design)
    else:
        production(design)


if __name__ == "__main__":
    main()
