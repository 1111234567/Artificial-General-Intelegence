BIRTHS = tuple(range(964800, 964808))
WORLDS = tuple(range(964880, 964888))
TRAIN, SILENT = 640, 80
DOSES = (0, 80, 240, TRAIN)
HISTORIES = ("A", "C")
SEED, DRAWS = 828539227, 20000
SOURCES = ("sparse_reacquire.py", "sparse_pair_switch.py", "sparse_pairs_model.py", "ring_logic_study.py",
           "dendrite_ports_graph.py", "unified_live_graph.py", "unified_live_graph_study.py",
           "graph_interactions.py", "mixture_world.py", "world.py")


def provenance():
    return dict(source_sha256={name: digest(Path(__file__).with_name(name)) for name in SOURCES},
                switch_sha256=digest(switch.EVIDENCE / "protocol.json"),
                recipe_source_sha256=digest(switch.MAIN / "development.json"))


def register(out):
    out.mkdir(parents=True, exist_ok=True)
    assert TRAIN == switch.REG["training_trials_per_stage"] and SILENT == switch.REG["silent_trials"]
    write(out / "reacquire-registered.json", dict(
        utc=datetime.now(timezone.utc).isoformat(), **provenance(), setup=switch.setup(),
        births=BIRTHS, worlds=WORLDS, initial_histories=HISTORIES, teaching_opportunities_per_phase=TRAIN,
        silent_probe_trials=SILENT, return_doses=DOSES, bootstrap=dict(seed=SEED, draws=DRAWS),
        design="A-B-A and C-B-A guided graphs share the same physical menus, exploration currents, initial graph and private world seeds, paired within the same birth and world. They differ only in the first 640 opportunities' taste rule. C rotates A's two rows of the four cross-pair coefficients by plus or minus 90 degrees with a private balanced sign assignment. The rotation preserves norm and makes A and C orthogonal, and is generated by signed permutation of the independent symmetric sensory coordinates. After the first stage, both histories face identical B on the distinct pair family {01,23}, then identical A on new meals. No context port, graph reset, training pause or rule flag is supplied. Silent forks do not change any live training state.",
        primary="Use the same new A dishes for all return checkpoints. Test A-history minus C-history after 0, 80 and 240 shared return teaching opportunities and A-history minus 50% at dose 0, a four-contrast two-sided 95% simultaneous percentile family. The dose is physical requests with truly observed receipts reported. Report the 640 endpoint descriptively. Early return benefit with a positive simultaneous interval may indicate history-dependent relearning. Call zero-taste A retention supported only if both zero-dose lower bounds exceed zero.",
        diagnostics="Report own-rule and common-A frozen scores immediately before B, B scores at 0 and 640, coverage at each probe, actual receipts throughout, and return counts. Score first physical contact to higher expected side with no contact counted incorrect. Pair by birth and world; independently resample both roots with replacement for 20000 paired draws. No parameter selection or seed selection follows observation.",
        scope="The two receipt histories can induce different behaviors and therefore different actual experiences in common B and A. This performance contrast measures history effects under self-selected contact, not an internal memory-mechanism ablation or a test of exact equivalence to chance.",
    ), exclusive=True)


def orthogonal_menu(menu, roots, *, probe=False):
    signs = {root: 1 - 2 * (index % 2) for index, root in enumerate(WORLDS)}
    direction = np.array([signs[root] for root in roots])[:, None]
    original = menu.weights
    rotated = np.column_stack((original[:, 2:], -original[:, :2])) * direction
    np.testing.assert_allclose(np.sum(original * rotated, axis=1), 0, atol=1e-12)
    np.testing.assert_allclose(np.linalg.norm(rotated, axis=1), 1, atol=1e-12)
    features = task.interactions(menu.chemicals * 2 - 1, task.CROSS)
    utility = np.einsum("btij,bj->bti", features, rotated)
    probability = (1 / (1 + np.exp(-task.TASTE_GAIN * utility))).astype(np.float32)
    uniforms = {root: np.random.default_rng([root, int(probe), 534508]).random((menu.body.trials, 2)) for root in set(roots)}
    realized = np.where(np.stack([uniforms[root] for root in roots]) < probability, 1, -1).astype(np.int8)
    return replace(menu, probability=probability, realized=realized, weights=rotated)


def physical_play(brain, menu, noise, offset, *, silent=False):
    mask, weight, receipts = brain.mask.copy(), brain.weight.copy(), brain.receipts.copy()
    codes, edits, stock = switch.play(brain, menu, noise, offset, silent=silent)
    contact, tick, actual, truth, shown = codes.transpose(2, 0, 1)
    hit = contact >= 0
    np.testing.assert_array_equal(hit, tick >= 0)
    np.testing.assert_array_equal(truth, menu.probability.argmax(axis=2))
    rewards = np.take_along_axis(menu.realized, contact.clip(min=0)[..., None], axis=2)[..., 0]
    np.testing.assert_array_equal(actual, np.where(hit, rewards, 0))
    if silent:
        assert not shown.any() and not (edits >= 0).any()
        np.testing.assert_array_equal(mask, brain.mask)
        np.testing.assert_array_equal(weight, brain.weight)
        np.testing.assert_array_equal(receipts, brain.receipts)
    else:
        np.testing.assert_array_equal(shown, actual)
        np.testing.assert_array_equal(brain.receipts - receipts, hit.sum(axis=1))
        assert not (edits[~hit] >= 0).any()
        audit_edits(mask, weight, edits, brain.mask, brain.weight)
        assert legal(brain.mask, brain.active["key"]).all()
    return codes, edits, stock


def simulate(birth_ids):
    roots = WORLDS * len(birth_ids)
    births = np.repeat(birth_ids, len(WORLDS))
    a_initial, first_noise = switch.meal(roots, 0)
    c_initial = orthogonal_menu(a_initial, roots)
    a_probe, first_probe_noise = switch.meal(roots, 0, probe=True)
    c_probe = orthogonal_menu(a_probe, roots, probe=True)
    b_menu = switch.meal(roots, 1)
    b_probe = switch.meal(roots, 1, probe=True)
    a_return, return_noise = switch.meal(roots, 2)
    return_probe = switch.meal(roots, 2, probe=True)
    np.testing.assert_array_equal(a_initial.weights, a_return.weights)
    np.testing.assert_array_equal(a_initial.weights, return_probe[0].weights)
    assert not np.array_equal(a_initial.chemicals[:, :SILENT], return_probe[0].chemicals)
    result = dict(birth=births, world=np.asarray(roots), A_coefficients=a_initial.weights,
                  C_coefficients=c_initial.weights, B_coefficients=b_menu[0].weights)

    for history, first, own_probe in (("A", a_initial, a_probe), ("C", c_initial, c_probe)):
        brain = switch.graph(births, roots, "guided")
        assert not len(brain.active) and not brain.state.any()

        def store_training(name, menu, noise, offset):
            codes, edits, stock = physical_play(brain, menu, noise, offset)
            result.update({f"{history}/{name}/train": codes, f"{history}/{name}/edits": edits,
                           f"{history}/{name}/stock": stock})

        def store_probe(name, menu, noise, offset):
            probe, _, _ = physical_play(brain, menu, noise, offset, silent=True)
            result[f"{history}/{name}"] = probe

        store_training("first", first, first_noise, 0)
        store_probe("own_initial_rule", own_probe, first_probe_noise, TRAIN)
        store_probe("A_before_B", a_probe, first_probe_noise, TRAIN)
        store_probe("B0", *b_probe, TRAIN)
        store_training("B", *b_menu, TRAIN)
        store_probe("B640", *b_probe, 2 * TRAIN)
        start = 0
        for dose in DOSES:
            if dose > start:
                span = slice(start, dose)
                store_training(f"return{dose}", switch.portion(a_return, span), return_noise[:, span], 2 * TRAIN + start)
            store_probe(f"A{dose}", *return_probe, 2 * TRAIN + dose)
            start = dose

    matching = ("A_before_B", "B0", "B640", *(f"A{d}" for d in DOSES), "B/train", *(f"return{d}/train" for d in DOSES[1:]))
    for name in matching:
        np.testing.assert_array_equal(result[f"A/{name}"][..., 3], result[f"C/{name}"][..., 3])
    return result


def summarize(chunks):
    n, m = len(BIRTHS), len(WORLDS)
    data = {field: np.concatenate([chunk[field] for chunk in chunks]) for field in chunks[0]}
    np.testing.assert_array_equal(data["birth"], np.repeat(BIRTHS, m))
    np.testing.assert_array_equal(data["world"], np.tile(WORLDS, n))
    probes = ("own_initial_rule", "A_before_B", "B0", "B640", *(f"A{d}" for d in DOSES))
    scores = {h: {p: switch.accuracy(data[f"{h}/{p}"]).reshape(n, m) for p in probes} for h in HISTORIES}
    means = {h: {p: dict(accuracy=float(scores[h][p].mean()),
                         coverage=float((data[f"{h}/{p}"][..., 0] >= 0).mean())) for p in probes} for h in HISTORIES}
    intervals = {f"A{d}_prior_A_minus_C": scores["A"][f"A{d}"] - scores["C"][f"A{d}"] for d in DOSES[:-1]}
    intervals["A0_prior_A_minus_chance"] = scores["A"]["A0"] - .5
    rng = np.random.default_rng(SEED)
    b = rng.integers(n, size=(DRAWS, n, 1))
    w = rng.integers(m, size=(DRAWS, 1, m))
    confidence = {name: [float(diff.mean()), *np.quantile(diff[b, w].mean(axis=(1, 2)), [.025 / 4, 1 - .025 / 4])]
                  for name, diff in intervals.items()}
    training = {}
    for history in HISTORIES:
        return_fields = tuple(f"return{d}" for d in DOSES[1:])
        counts = {stage: int(np.count_nonzero(data[f"{history}/{stage}/train"][..., 4]))
                  for stage in ("first", "B", *return_fields)}
        training[history] = dict(
            shown_receipts=counts,
            total_teaching_opportunities=n * m * 3 * TRAIN,
            final_active_pairs={stage: float(data[f"{history}/{stage}/stock"][:, -1].mean())
                                for stage in ("first", "B", *return_fields)},
        )
    return dict(means=means, primary=confidence, training=training,
                zero_taste_retention_supported=bool(min(confidence["A0_prior_A_minus_C"][1],
                                                       confidence["A0_prior_A_minus_chance"][1]) > 0))


def confirm(out, workers):
    registered = out / "reacquire-registered.json"
    protocol = read(registered)
    if any(protocol[key] != value for key, value in provenance().items()):
        raise RuntimeError("Registered source or inherited recipe changed")
    groups = [BIRTHS[i:i + 2] for i in range(0, len(BIRTHS), 2)]
    with ProcessPoolExecutor(max_workers=workers) as pool:
        chunks = list(pool.map(simulate, groups))
    summary = summarize(chunks)
    path = out / "reacquire-raw.zip"
    with ZipFile(path, "x") as archive:
        fingerprints = {}
        for group, chunk in zip(groups, chunks, strict=True):
            buf = BytesIO()
            np.savez_compressed(buf, **chunk)
            name = f"{group[0]}.npz"
            archive.writestr(name, buf.getvalue())
            fingerprints[name] = sha256(buf.getvalue()).hexdigest()
    write(out / "reacquire-summary.json", dict(summary, registered_sha256=digest(registered),
                                                raw_sha256=digest(path), entries_sha256=fingerprints), exclusive=True)
    print(summary, flush=True)


def audit(out):
    summary = read(out / "reacquire-summary.json")
    path = out / "reacquire-raw.zip"
    assert digest(path) == summary["raw_sha256"]
    assert digest(out / "reacquire-registered.json") == summary["registered_sha256"]
    with ZipFile(path) as archive:
        chunks = []
        assert archive.namelist() == list(summary["entries_sha256"])
        for name, fingerprint in summary["entries_sha256"].items():
            payload = archive.read(name)
            assert sha256(payload).hexdigest() == fingerprint
            with np.load(BytesIO(payload), allow_pickle=False) as content:
                chunks.append(dict(content))
    for field, value in summarize(chunks).items():
        assert summary[field] == value
    print("Verified frozen contrasts, summary and all raw fingerprints", flush=True)


def main():
    parser = ArgumentParser(description=__doc__)
    parser.add_argument("stage", choices=("register", "confirm", "audit"))
    parser.add_argument("--out", type=Path, default=switch.EVIDENCE)
    parser.add_argument("--workers", type=int, default=4)
    args = parser.parse_args()
    if args.stage == "confirm":
        confirm(args.out, args.workers)
    else:
        {"register": register, "audit": audit}[args.stage](args.out)


if __name__ == "__main__":
    main()
